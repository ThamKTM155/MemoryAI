def extract_lessons(text):

    results = []

    keywords = [

        "bài học",

        "lesson",

        "kinh nghiệm"

    ]

    for line in text.splitlines():

        lower = line.lower()

        if any(k in lower for k in keywords):

            results.append(line.strip())

    return results



import os
import re
import json
from pathlib import Path
from datetime import datetime

def load_diary(path):

    with open(
        path,
        "r",
        encoding="utf-8"
    ) as f:

        return f.read()

def extract_date(filename):

    match = re.search(
        r"\d{4}-\d{2}-\d{2}",
        filename
    )

    if match:

        return match.group()

    return Path(filename).stem
def extract_keywords(text):

    keywords = []

    patterns = [

        "AutoYouTube",
        "MemoryAI",
        "ThamAI",
        "Dashboard",
        "Winner AI",
        "OpenRouter",
        "Github",
        "Production"

    ]

    for p in patterns:

        if p.lower() in text.lower():

            keywords.append(p)

    return keywords


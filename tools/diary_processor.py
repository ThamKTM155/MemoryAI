def extract_decisions(text):

    results = []

    keywords = [

        "quyết định",

        "freeze",

        "complete",

        "pass",

        "chốt"

    ]

    for line in text.splitlines():

        lower = line.lower()

        if any(k in lower for k in keywords):

            results.append(line.strip())
    results = list(dict.fromkeys(results))
    
    return results


